`timescale 1ns/1ps

module bit4_alu_tb;

reg en;
reg [3:0] a, b;
reg [2:0] opcode;

wire [3:0] out;
wire cout;

localparam period = 20;

// DUT Instantiation
bit4_alu uut (
    .en(en),
    .a(a),
    .b(b),
    .opcode(opcode),
    .out(out),
    .cout(cout)
);

initial begin

    // Initialize
    en = 0;
    a = 4'b0000;
    b = 4'b0000;
    opcode = 3'b000;

    #period;

    // ==========================================
    // ADD (opcode = 000)
    // F + F = 1E → out = E, cout = 1
    // ==========================================
    a = 4'b1111;
    b = 4'b1111;
    opcode = 3'b000;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // SUB (opcode = 001)
    // 0 - 1 = F (2's complement)
    // out = F, cout = 0
    // ==========================================
    a = 4'b0000;
    b = 4'b0001;
    opcode = 3'b001;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // AND (opcode = 010)
    // C & 3 = 0
    // 1100 & 0011 = 0000
    // out = 0
    // ==========================================
    a = 4'b1100;
    b = 4'b0011;
    opcode = 3'b010;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // OR (opcode = 011)
    // C | 3 = F
    // 1100 | 0011 = 1111
    // out = F
    // ==========================================
    a = 4'b1100;
    b = 4'b0011;
    opcode = 3'b011;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // XOR (opcode = 100)
    // C ^ 3 = F
    // 1100 ^ 0011 = 1111
    // out = F
    // ==========================================
    a = 4'b1100;
    b = 4'b0011;
    opcode = 3'b100;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // NOT (opcode = 101)
    // ~A
    // ~1010 = 0101
    // out = 5
    // ==========================================
    a = 4'b1010;
    opcode = 3'b101;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // INC (opcode = 110)
    // A + 1
    // 1111 + 1 = 0000, cout = 1
    // out = 0
    // ==========================================
    a = 4'b1111;
    opcode = 3'b110;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    // ==========================================
    // DEC (opcode = 111)
    // A - 1
    // 0000 - 1 = 1111
    // out = F
    // ==========================================
    a = 4'b0000;
    opcode = 3'b111;
    #1 en = 1'b1;
    #5 en = 1'b0;

    #period;

    $finish;

end

endmodule